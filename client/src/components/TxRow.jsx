import { useState } from 'react';
import { api } from '../api.js';
import { useApp } from '../context.jsx';
import { listDate, rowState } from '../cardLogic.js';
import { dateLabel, dateLong, relativeDay, todayYMD, weekday } from '../format.js';
import { useWorkspace } from '../workspace.jsx';
import { AlertBell } from './Alerts.jsx';
import { ReceiptsModal } from './Receipts.jsx';
import { Avatar, AvatarStack, CategoryDot, Icon } from './ui.jsx';
import { t, tn } from '../i18n/translate.js';

/** One payment row with pay/unpay, edit and delete actions. */
export default function TxRow({ tx, onChange, onEdit, compact }) {
  const { money, notify } = useApp();
  const { isGroup } = useWorkspace();
  // A row can be listed in its purchase month only (`purchase_only`): it is a card purchase that counts later, when the bill is paid.
  const purchaseOnly = !!tx.purchase_only;
  const state = rowState(tx, todayYMD());
  const overdue = state === 'overdue';
  const income = tx.type === 'income';
  const card = tx.pay_method === 'credit_card';
  const shownDate = listDate(tx);
  const inInstallments = purchaseOnly && tx.plan_installment_count > 1;
  const title = inInstallments ? tx.description.replace(/ \(\d+\/\d+\)$/, '') : tx.description;
  const shownAmount = inInstallments && tx.plan_purchase_amount != null ? tx.plan_purchase_amount : tx.amount;
  const [receiptsOpen, setReceiptsOpen] = useState(false);
  const receipts = tx.receipt_count ?? 0;

  async function setStatus(status) {
    try {
      await api.patch(`/transactions/${tx.id}/status`, { status });
      onChange();
    } catch (e) {
      notify(e.message, 'error');
    }
  }

  async function remove() {
    const recurring = tx.recurring_id && tx.status !== 'skipped';
    const msg = recurring
      ? t('Skip "{description}" on {dateLabel}? The recurring item itself stays.', { description: tx.description, dateLabel: dateLabel(tx.date) })
      : t('Delete "{description}"?', { description: tx.description });
    if (!window.confirm(msg)) return;
    try {
      await api.del(`/transactions/${tx.id}${tx.status === 'skipped' ? '?hard=1' : ''}`);
      notify(recurring ? t('Occurrence skipped') : t('Payment deleted'));
      onChange();
    } catch (e) {
      notify(e.message, 'error');
    }
  }

  return (
    <div className={`tx-row${tx.status === 'skipped' ? ' skipped' : ''}${compact ? ' compact' : ''}${purchaseOnly ? ' purchase-only' : ''}${state ? ` is-${state}` : ''}`}>
      <div className="tx-date">
        <strong>{dateLabel(shownDate)}</strong>
        <span className={overdue ? 'neg' : 'muted'}>{compact || overdue ? relativeDay(shownDate) : weekday(shownDate)}</span>
      </div>
      <div className="tx-main">
        <div className="tx-title">
          {title}
          {tx.source === 'recurring' && (
            <span className="badge" title={t('Generated by a recurring item')}>
              <Icon name="repeat" size={12} /> {t('Recurring')}
            </span>
          )}
          {tx.source === 'installment' && (
            <span className="badge" title={t('Part of an installment plan')}>
              <Icon name="card" size={12} /> {t('Installment')}
            </span>
          )}
          {tx.source === 'adjustment' && (
            <span className="badge" title={t('Added to match the bank balance. Delete it to undo.')}>
              <Icon name="check" size={12} /> {t('Adjustment')}
            </span>
          )}
          {tx.import_batch_id != null && (
            <span className="badge" title={t('Added from a bank statement. You can undo a whole import from Import statement.')}>
              <Icon name="upload" size={12} /> {t('Imported')}
            </span>
          )}
          {tx.source === 'debt' && (
            <span className="badge" title={tx.type === 'income' ? t('Money paid back to you. It counts in your balance, not as earnings.') : t('Part of paying off a debt')}>
              <Icon name="debt" size={12} /> {tx.type === 'income' ? t('Paid back') : t('Debt')}
            </span>
          )}
          {tx.source === 'loan' && (
            <span className="badge" title={t('Money you lent. It counts in your balance, not as spending.')}>
              <Icon name="debt" size={12} /> {t('Loan')}
            </span>
          )}
          {card && (
            <span className="badge card" title={t('Bought {dateLong} with the credit card. It counts when the bill is paid, on {dateLong2}.', { dateLong: dateLong(tx.charged_on), dateLong2: dateLong(tx.date) })} data-purchase-only={purchaseOnly || undefined}>
              <Icon name="card" size={12} /> {t('Credit card')}
            </span>
          )}
          {receipts > 0 && (
            <button className="receipt-chip" onClick={() => setReceiptsOpen(true)} aria-label={tn(receipts, '{n} receipt for {description}', '{n} receipts for {description}', { description: tx.description })} title={t('View receipts')}>
              <Icon name="paperclip" size={12} /> {receipts}
            </button>
          )}
          {tx.status === 'skipped' && <span className="badge">{t('Skipped')}</span>}
        </div>
        <div className="tx-meta">
          <CategoryDot color={tx.category_color} name={tx.category_name} />
          {purchaseOnly && (
            <strong className="counts-on">
              {inInstallments ? t('paid in {plan_installment_count} installments, the first on {dateLabel}', { plan_installment_count: tx.plan_installment_count, dateLabel: dateLabel(tx.date) }) : t('counts on {dateLabel}, when the bill is paid', { dateLabel: dateLabel(tx.date) })}
            </strong>
          )}
          {card && !purchaseOnly && tx.charged_on !== tx.date && <span className="muted">{t('bought {dateLabel}', { dateLabel: dateLabel(tx.charged_on) })}</span>}
          {isGroup && tx.member_name && (
            <span className="who" title={income ? t('Whose income') : t('Paid by')}>
              <Avatar user={{ name: tx.member_name, avatar_url: tx.member_avatar }} size={16} />
              {income ? t('from {name}', { name: tx.member_name.split(' ')[0] }) : t('paid by {name}', { name: tx.member_name.split(' ')[0] })}
            </span>
          )}
          {tx.participants?.length > 0 && (
            <span className="who" title={tx.participants.map((p) => `${p.name}: ${money(p.share)}`).join('\n')}>
              <AvatarStack people={tx.participants} size={16} limit={3} />
              {t('with {join}', { join: tx.participants.map((p) => p.name.split(' ')[0]).join(', ') })}
            </span>
          )}
        </div>
      </div>
      <div className={`tx-amount num ${income ? 'pos' : ''}`}>
        {income ? '+' : '−'}
        {money(shownAmount)}
      </div>
      <div className="tx-actions">
        {tx.status === 'pending' && !purchaseOnly && <AlertBell tx={tx} onChange={onChange} />}
        {tx.receipt_count !== undefined && !compact && tx.status !== 'skipped' && receipts === 0 && (
          <button className="btn icon ghost" onClick={() => setReceiptsOpen(true)} aria-label={t('Attach a receipt to {description}', { description: tx.description })} title={t('Attach a receipt')}>
            <Icon name="paperclip" size={16} />
          </button>
        )}
        {tx.status === 'pending' && !purchaseOnly && (
          <button className="btn sm primary-soft" onClick={() => setStatus('paid')}>
            <Icon name="check" size={14} /> {income ? t('Received') : t('Mark paid')}
          </button>
        )}
        {tx.status === 'paid' && !purchaseOnly && (
          <button className="btn sm paid" onClick={() => setStatus('pending')} title={t('Click to mark as not paid')}>
            <Icon name="check" size={14} /> {income ? t('Received') : t('Paid')}
          </button>
        )}
        {tx.status === 'skipped' && (
          <button className="btn sm" onClick={() => setStatus('pending')}>
            <Icon name="undo" size={14} /> {t('Restore')}
          </button>
        )}
        {onEdit && (
          <button className="btn icon ghost" onClick={() => onEdit(tx)} aria-label={t('Edit {description}', { description: tx.description })}>
            <Icon name="edit" />
          </button>
        )}
        {!compact && (
          <button className="btn icon ghost danger-hover" onClick={remove} aria-label={`${tx.recurring_id ? t('Skip') : t('Delete')} ${tx.description}`}>
            <Icon name={tx.recurring_id && tx.status !== 'skipped' ? 'skip' : 'trash'} />
          </button>
        )}
      </div>
      {receiptsOpen && <ReceiptsModal tx={tx} onClose={() => setReceiptsOpen(false)} onChange={onChange} />}
    </div>
  );
}
